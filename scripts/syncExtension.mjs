#!/usr/bin/env node
/**
 * Generate the extension's copy of the shared field-label module (audit A12).
 *
 *   node scripts/syncExtension.mjs          write extension/fieldLabels.js
 *   node scripts/syncExtension.mjs --check  exit 1 if it is out of date
 *
 * The extension is loaded as plain scripts, so the ES module in
 * src/shared/fieldLabels.js is wrapped as a classic script that sets
 * globalThis.JobAgentFieldLabels. A test (extensionSharedMapping) fails when the
 * committed copy differs from what this produces.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'src', 'shared', 'fieldLabels.js');
const TARGET = join(ROOT, 'extension', 'fieldLabels.js');

/** The classic-script text for the extension. */
export function generateExtensionFieldLabels() {
  const body = readFileSync(SOURCE, 'utf8').replace(/^export\s+/gm, '');
  return [
    '// GENERATED by scripts/syncExtension.mjs from src/shared/fieldLabels.js. Do not edit; run `npm run sync:extension`.',
    '(() => {',
    body.replace(/\n+$/, ''),
    '  globalThis.JobAgentFieldLabels = { classifyLabel, FIELD_ALIASES };',
    '})();',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generateExtensionFieldLabels();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(TARGET, 'utf8'); } catch { /* missing */ }
    if (current !== next) { console.error('extension/fieldLabels.js is out of date: run `npm run sync:extension`'); process.exit(1); }
    console.log('extension/fieldLabels.js is current');
  } else {
    writeFileSync(TARGET, next);
    console.log('wrote extension/fieldLabels.js');
  }
}
